// Fail closed: an unregistered hook under go/hybrid is an error, the run
// aborts non-zero, and neither settings.json nor .yakos.yml is touched.
func TestHooksImpl_UnregisteredHookFailsClosed(t *testing.T) {
	for _, tc := range []struct {
		impl    HooksImpl
		missing string
	}{
		{HooksImplGo, "path-log"},
		{HooksImplHybrid, "cycle-counter"},
	} {
		t.Run(string(tc.impl), func(t *testing.T) {
			orig := registeredHooks
			t.Cleanup(func() { registeredHooks = orig })
			registeredHooks = func() []string {
				var out []string
				for _, n := range registry.Names() {
					if n != tc.missing {
						out = append(out, n)
					}
				}
				return out
			}
			proj, home := fixtureProject(t, "proj-missing-settings")
			before := readSettings(t, proj)
			hooksBefore, _ := os.ReadDir(filepath.Join(proj, "scripts"))
			_, err := runImpl(t, proj, home, tc.impl)
			if err == nil {
				t.Fatal("want error for unregistered hook, got nil")
			}
			if !strings.Contains(err.Error(), tc.missing) || !strings.Contains(err.Error(), "no Go implementation registered") {
				t.Fatalf("error does not name the hook: %v", err)
			}
			if !bytes.Equal(before, readSettings(t, proj)) {
				t.Fatal("settings.json modified despite refusal")
			}
			if _, err := os.Stat(filepath.Join(proj, ".yakos.yml")); err == nil {
				t.Fatal(".yakos.yml persisted despite refusal")
			}
			if hooksAfter, _ := os.ReadDir(filepath.Join(proj, "scripts")); len(hooksAfter) != len(hooksBefore) {
				t.Fatal("hook scripts synced despite refusal")
			}
		})
	}
}

