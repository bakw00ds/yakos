// Consistency with the real registry: the hybrid allowlist is sorted, every
// entry is registered and marked GoReady there, and go mode covers every
// hook in the shipped template.
func TestHooksImpl_AllowlistAndTemplateAgreeWithRegistry(t *testing.T) {
	reg := map[string]registry.Entry{}
	for _, e := range registry.All() {
		reg[e.Name] = e
	}
	var want []string
	for _, e := range registry.All() {
		if e.GoReady {
			want = append(want, e.Name)
		}
	}
	got := GoReadyAllowlist()
	if strings.Join(got, ",") != strings.Join(want, ",") {
		t.Errorf("hybrid list %v != registry GoReady set %v", got, want)
	}
	if !isAllowlisted("path-log") {
		t.Error("path-log (GoReady since A-1) missing from the hybrid list")
	}
	for i, n := range got {
		if i > 0 && got[i-1] >= n {
			t.Errorf("hybrid list not sorted at %q", n)
		}
		if _, ok := reg[n]; !ok {
			t.Errorf("%q not registered", n)
		}
	}
	data, err := os.ReadFile(filepath.Join(hooksImplRepoRoot(t), "lib", "settings", "settings.template.json")) //nolint:gosec
	if err != nil {
		t.Fatal(err)
	}
	var tmpl map[string]any
	if err := json.Unmarshal(data, &tmpl); err != nil {
		t.Fatal(err)
	}
	if err := ValidateHooksImpl(HooksImplGo, tmpl); err != nil {
		t.Fatalf("shipped template has hooks with no Go implementation: %v", err)
	}
}

