func TestHooksImpl_PersistedValueHonoredThenFlagOverrides(t *testing.T) {
	proj, home := fixtureProject(t, "proj-missing-settings")
	if _, err := runImpl(t, proj, home, HooksImplHybrid); err != nil {
		t.Fatal(err)
	}
	if v, ok, err := ReadPersistedHooksImpl(proj); err != nil || !ok || v != HooksImplHybrid {
		t.Fatalf("persisted = %q,%v,%v; want hybrid", v, ok, err)
	}
	hybrid := readSettings(t, proj)

	// No flag: persisted hybrid is kept.
	out, err := runImpl(t, proj, home, "")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(out, "hooks-impl: hybrid (persisted)") {
		t.Fatalf("output does not report persisted hybrid:\n%s", out)
	}
	if !bytes.Equal(hybrid, readSettings(t, proj)) {
		t.Fatal("no-flag run changed a hybrid settings.json")
	}

	// Flag overrides and re-persists.
	if _, err := runImpl(t, proj, home, HooksImplGo); err != nil {
		t.Fatal(err)
	}
	if v, _, _ := ReadPersistedHooksImpl(proj); v != HooksImplGo {
		t.Fatalf("persisted after override = %q, want go", v)
	}
	if _, err := runImpl(t, proj, home, ""); err != nil {
		t.Fatal(err)
	}
	for _, c := range commands(t, readSettings(t, proj)) {
		if !strings.Contains(c, testBin+" hook run ") {
			t.Fatalf("persisted go not honored: %s", c)
		}
	}
}

