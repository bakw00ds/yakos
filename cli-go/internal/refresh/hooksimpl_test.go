// Hook order inside each event must be identical across impls.
func TestHooksImpl_HookOrderUnchanged(t *testing.T) {
	names := func(cmds []string) []string {
		var out []string
		for _, c := range cmds {
			ev := c[:strings.Index(c, "|")]
			cmd := c[strings.Index(c, "|")+1:]
			n := hookNameFromTemplateCommand(cmd)
			if g, ok := goHookName(cmd); ok {
				n = g
			}
			out = append(out, ev+"|"+n)
		}
		return out
	}
	base, home := fixtureProject(t, "proj-missing-settings")
	if _, err := runImpl(t, base, home, HooksImplBash); err != nil {
		t.Fatal(err)
	}
	want := names(commands(t, readSettings(t, base)))
	for _, impl := range []HooksImpl{HooksImplHybrid, HooksImplGo} {
		if _, err := runImpl(t, base, home, impl); err != nil {
			t.Fatal(err)
		}
		got := names(commands(t, readSettings(t, base)))
		if strings.Join(got, ",") != strings.Join(want, ",") {
			t.Fatalf("%s reordered hooks:\n got %v\nwant %v", impl, got, want)
		}
	}
}

