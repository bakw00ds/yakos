func copyTree(t *testing.T, src, dst string) {
	t.Helper()
	err := filepath.Walk(src, func(p string, fi os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(src, p)
		target := filepath.Join(dst, rel)
		if fi.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		data, err := os.ReadFile(p) //nolint:gosec
		if err != nil {
			return err
		}
		return os.WriteFile(target, data, 0o644) //nolint:gosec
	})
	if err != nil {
		t.Fatalf("copyTree: %v", err)
	}
}

// fixtureProject copies a stock refresh fixture into a temp project.
func fixtureProject(t *testing.T, name string) (proj, home string) {
	t.Helper()
	tmp := t.TempDir()
	proj = filepath.Join(tmp, "project")
	home = filepath.Join(tmp, "home")
	for _, d := range []string{proj, filepath.Join(home, ".claude", "agents")} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	copyTree(t, filepath.Join("..", "..", "cmd", "yakos", "testdata", "fixtures", "refresh", name), proj)
	return proj, home
}

func runImpl(t *testing.T, proj, home string, impl HooksImpl) (string, error) {
	t.Helper()
	var buf bytes.Buffer
	_, err := Run(Config{
		YakosRoot:    hooksImplRepoRoot(t),
		ProjectPaths: []string{proj},
		HooksImpl:    impl,
		YakosBinary:  testBin,
		Writer:       &buf,
		ErrWriter:    &buf,
		HomeDir:      home,
	})
	return buf.String(), err
}

func readSettings(t *testing.T, proj string) []byte {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(proj, ".claude", "settings.json")) //nolint:gosec
	if err != nil {
		t.Fatal(err)
	}
	return b
}

// commands returns every hook command in settings, in document order per
// event (events sorted), as "event|command".
func commands(t *testing.T, data []byte) []string {
	t.Helper()
	var m map[string]any
	if err := json.Unmarshal(data, &m); err != nil {
		t.Fatal(err)
	}
	var out []string
	hm := hooksMap(m)
	events := make([]string, 0, len(hm))
	for e := range hm {
		events = append(events, e)
	}
	sortStrings(events)
	for _, e := range events {
		for _, en := range asList(hm[e]) {
			for _, h := range asList(hooksList(toMap(en))) {
				out = append(out, e+"|"+commandOf(toMap(h)))
			}
		}
	}
	return out
}

func sortStrings(s []string) {
	for i := 1; i < len(s); i++ {
		for j := i; j > 0 && s[j] < s[j-1]; j-- {
			s[j], s[j-1] = s[j-1], s[j]
		}
	}
}

func isAllowlisted(name string) bool {
	for _, n := range GoReadyAllowlist() {
		if n == name {
			return true
		}
	}
	return false
}

